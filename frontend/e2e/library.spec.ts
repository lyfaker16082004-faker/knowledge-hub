test('download, save and personal history persist after reload',async({page})=>{
 await page.goto('/#documents?q=Java');
 const documentLink=page.getByRole('link',{name:'Xem tài liệu: Java căn bản: từ biến đến lập trình hướng đối tượng',exact:true});
 await expect(documentLink).toBeVisible();await documentLink.click();
 await page.getByRole('button',{name:'Đăng nhập để tải',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Chào bạn trở lại 👋'})).toBeVisible();
 await page.getByRole('button',{name:'Tạo tài khoản',exact:true}).first().click();
 await page.getByLabel('Tên đăng nhập',{exact:true}).fill(username);
 await page.getByLabel('Địa chỉ email').fill(`${username}@example.test`);
 await page.getByLabel('Mật khẩu',{exact:true}).fill('Library-browser-password-2026!');
 await page.getByLabel('Xác nhận mật khẩu',{exact:true}).fill('Library-browser-password-2026!');
 await page.getByRole('button',{name:'Tạo tài khoản',exact:true}).last().click();
 await expect(page.getByRole('heading',{name:'Java căn bản: từ biến đến lập trình hướng đối tượng',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Lưu để đọc sau',exact:true}).click();
 await expect(page.getByRole('button',{name:'Đã lưu tài liệu',exact:true})).toBeVisible();
 const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Tải tài liệu',exact:true}).click()]);
 expect(download.suggestedFilename()).toBe('java-can-ban.md');
 const path=await download.path();expect(readFileSync(path!,'utf8')).toContain('Xin chào, Knowledge Hub!');
 await page.goto('/#mine');
 await expect(page.getByRole('heading',{name:'Trang của tôi',exact:true})).toBeVisible();
 await expect(page.locator('.history-row')).toHaveCount(1);
 await expect(page.locator('.history-row')).toContainText('Java căn bản');
 await page.reload();await expect(page.locator('.history-row')).toHaveCount(1);
 await page.screenshot({path:'test-results/my-library-desktop.png',fullPage:true});
 await page.getByRole('tab',{name:'Đã lưu',exact:true}).click();
 await expect(page.locator('.document-card')).toHaveCount(1);
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.screenshot({path:'test-results/my-library-mobile.png',fullPage:true});
 await page.goto('/#documents?category=1');
 await page.goto('/#documents?q=module');
 await page.getByRole('link',{name:'Xem tài liệu: Thiết kế module Spring Boot có kiểm thử',exact:true}).click();
 await expect(page.getByRole('button',{name:'Cần quyền truy cập',exact:true})).toBeDisabled();
 await expect(page.locator('.paid-note')).toContainText('Thanh toán trực tuyến chưa được mở');
});